import type { Metadata } from 'next';
import { activateTotp } from '@/app/conta/actions';
import { Button, Card, Notice, inputClass } from '@/components/ui';
import type { MfaStatus } from '@/lib/account';
import { accountApi } from '@/lib/account';
import { api } from '@/lib/api';

export const metadata: Metadata = { title: 'Segurança' };

export default async function SecurityPage({
  searchParams,
}: {
  searchParams: Promise<{ erro?: string; ativada?: string; senha?: string }>;
}) {
  const { erro, ativada, senha } = await searchParams;
  const [status, totp] = await Promise.all([api<MfaStatus>('care/mfa/'), accountApi('account/authenticators/totp')]);
  const active = totp.status === 200;

  return (
    <div className="flex flex-col gap-6">
      <div>
        <h1 className="text-2xl font-bold">Segurança</h1>
        <p className="text-sm text-gray-600">
          A verificação em duas etapas pede, além do login, um código do aplicativo autenticador do seu celular.
        </p>
      </div>
      {status.required && (
        <Notice tone="error">
          Contas de profissionais precisam da verificação em duas etapas para acessar os dados dos pacientes. Ative abaixo para continuar.
        </Notice>
      )}
      {erro && <Notice tone="error">{erro}</Notice>}
      {active ? <Active fresh={Boolean(ativada)} /> : <Setup secret={totp.json?.meta?.secret} url={totp.json?.meta?.totp_url} askPassword={Boolean(senha)} />}
    </div>
  );
}

async function Active({ fresh }: { fresh: boolean }) {
  const codes = await accountApi('account/authenticators/recovery-codes');
  const unused: string[] = codes.json?.data?.unused_codes ?? [];
  return (
    <Card title="Verificação em duas etapas ativada">
      <div className="flex flex-col gap-3 text-sm">
        {fresh && <Notice tone="success">Pronto: a verificação em duas etapas está ativada.</Notice>}
        <p>A cada login, depois do Google ou da senha, o ALMOVA pede o código do aplicativo autenticador.</p>
        <details open={fresh} className="rounded-xl border border-navy-100 p-3">
          <summary className="cursor-pointer font-semibold">Códigos de recuperação ({unused.length})</summary>
          <p className="mt-2 text-gray-600">
            Guarde em lugar seguro. Cada código entra uma vez, se você estiver sem o celular.
          </p>
          <ul aria-label="Códigos de recuperação" className="mt-2 grid grid-cols-2 gap-1 font-mono">
            {unused.map(code => (
              <li key={code}>{code}</li>
            ))}
          </ul>
        </details>
      </div>
    </Card>
  );
}

async function Setup({ secret, url, askPassword }: { secret?: string; url?: string; askPassword: boolean }) {
  if (!secret || !url) {
    return <Notice tone="error">Não foi possível preparar a verificação agora. Recarregue a página.</Notice>;
  }
  const qr = await api<{ svg: string }>('care/mfa/qr/', { method: 'POST', body: { url } });
  return (
    <Card title="Ativar a verificação em duas etapas">
      <ol className="flex list-decimal flex-col gap-4 pl-5 text-sm">
        <li>Instale um aplicativo autenticador no celular (Google Authenticator, Microsoft Authenticator ou outro).</li>
        <li>
          No aplicativo, leia o código QR abaixo. Sem câmera, digite a chave:
          <div className="mt-3 flex flex-wrap items-center gap-4">
            {/* SVG generated by the server from the setup link */}
            <div className="size-44 rounded-xl border border-navy-100 bg-white p-2" dangerouslySetInnerHTML={{ __html: qr.svg }} />
            <code aria-label="Chave do autenticador" className="break-all rounded-lg bg-navy-100/50 px-2 py-1 text-base">
              {secret}
            </code>
          </div>
        </li>
        <li>
          Digite o código de 6 dígitos que o aplicativo mostra.
          <form action={activateTotp} className="mt-3 flex flex-col gap-3">
            <label className="flex flex-col gap-1 font-medium">
              Código do aplicativo
              <input name="code" required inputMode="numeric" autoComplete="one-time-code" maxLength={6} className={`${inputClass} max-w-40 tracking-widest`} />
            </label>
            <label className="flex flex-col gap-1 font-medium">
              Senha da conta {askPassword ? '' : '(só se a sua conta tiver senha; com Google, deixe em branco)'}
              <input name="password" type="password" required={askPassword} autoComplete="current-password" className={`${inputClass} max-w-xs`} />
            </label>
            <div>
              <Button type="submit">Ativar</Button>
            </div>
          </form>
        </li>
      </ol>
    </Card>
  );
}
