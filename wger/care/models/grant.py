# Standard Library
import uuid

# Django
from django.contrib.auth.models import User
from django.db import models
from django.utils.translation import gettext_lazy as _

# wger
from wger.care.models.relationship import CareRelationship


class SharingScope(models.TextChoices):
    """
    Read-only data a patient can share with a professional of another discipline
    """

    TRAINING_SCHEDULE = 'training.schedule', _('Training days, times and frequency')
    TRAINING_ADHERENCE = 'training.adherence', _('Completed training sessions')
    NUTRITION_GOALS = 'nutrition.goals', _('Nutrition goals and meal times')
    NUTRITION_ADHERENCE = 'nutrition.adherence', _('Food diary summary')
    PHYSIO_PAIN = 'physio.pain', _('Pain records summary')
    BODY_MEASUREMENTS = 'body.measurements', _('Body weight and measurements')
    NOTES = 'notes.multidisciplinary', _('Multidisciplinary notes')


class AccessGrant(models.Model):
    """
    A scope the patient shares with one of their professionals, until revoked
    """

    class Meta:
        ordering = ['-granted_at']
        constraints = [
            models.UniqueConstraint(
                fields=['relationship', 'scope'],
                condition=models.Q(revoked_at__isnull=True),
                name='unique_active_grant',
            ),
        ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4)

    relationship = models.ForeignKey(
        CareRelationship,
        on_delete=models.CASCADE,
        related_name='grants',
    )

    scope = models.CharField(max_length=40, choices=SharingScope.choices)

    granted_at = models.DateTimeField(auto_now_add=True)

    revoked_at = models.DateTimeField(null=True, blank=True)

    consent_version = models.CharField(max_length=20, blank=True)

    def __str__(self):
        return f'{self.scope} → {self.relationship_id}'

    def get_owner_object(self):
        return None


class ConsentKind(models.TextChoices):
    TERMS = 'terms', _('Terms of use and privacy policy')
    HEALTH_DATA = 'health_data', _('Processing of health data')
    CARE_RELATIONSHIP = 'care_relationship', _('Follow-up by a professional')
    SHARING = 'sharing', _('Sharing between professionals')
    AI = 'ai', _('Summaries generated by artificial intelligence')
    WHATSAPP = 'whatsapp', _('Notifications via WhatsApp')


class ConsentRecord(models.Model):
    """
    A consent given by a user, kept after revocation as evidence
    """

    class Meta:
        ordering = ['-accepted_at']

    id = models.UUIDField(primary_key=True, default=uuid.uuid4)

    user = models.ForeignKey(User, on_delete=models.CASCADE, related_name='consents')

    kind = models.CharField(max_length=20, choices=ConsentKind.choices)

    version = models.CharField(max_length=20)

    reference = models.CharField(
        max_length=64,
        blank=True,
        help_text='ID of the object the consent is about, e.g. a care relationship',
    )

    accepted_at = models.DateTimeField(auto_now_add=True)

    revoked_at = models.DateTimeField(null=True, blank=True)

    def __str__(self):
        return f'{self.user} {self.kind} v{self.version}'

    def get_owner_object(self):
        return self
